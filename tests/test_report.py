"""
The published report must be built from results.json alone: every view has
data, every number shown is in results.json, and the page says the data is
synthetic. Built from the seeded fixture, so no market data is involved.
"""

import json
import re
from html.parser import HTMLParser
from pathlib import Path

import pytest

from quantsim.cli import report
from tests.fixtures import make_fixture

BENCHMARK = Path(__file__).parent.parent / "benchmarks" / "results.json"
VIEWS = ["fill_timing", "walk_forward", "sharpe_uncertainty", "cost_sensitivity"]


class VisibleText(HTMLParser):
    def __init__(self):
        super().__init__()
        self.skip = 0
        self.chunks = []

    def handle_starttag(self, tag, attrs):
        if tag in ("script", "style"):
            self.skip += 1

    def handle_endtag(self, tag):
        if tag in ("script", "style"):
            self.skip -= 1

    def handle_data(self, data):
        if not self.skip:
            self.chunks.append(data)


@pytest.fixture(scope="module")
def built(tmp_path_factory):
    tmp = tmp_path_factory.mktemp("report")
    prices = make_fixture.main(["--out", str(tmp / "synthetic_prices.csv")])
    out = tmp / "site"
    report.main(
        [
            "--prices",
            str(prices),
            "--strategy",
            "sma",
            "momentum",
            "--out",
            str(out),
            "--benchmark",
            str(BENCHMARK),
        ]
    )
    results = json.loads((out / "results.json").read_text())
    page = (out / "index.html").read_text()
    return results, page


def test_every_view_has_data(built):
    results, _ = built
    assert set(results["strategies"]) == {"sma", "momentum"}
    for strategy in results["strategies"].values():
        for view in VIEWS:
            assert strategy[view], view
            assert strategy[view]["takeaway"], view
        assert (
            len(strategy["fill_timing"]["dates"])
            == len(strategy["fill_timing"]["next_bar_open"])
            > 0
        )
        assert len(strategy["walk_forward"]["oos_equity"]) > 0
        assert (
            sum(strategy["sharpe_uncertainty"]["counts"])
            == strategy["sharpe_uncertainty"]["n_simulations"]
        )
        assert strategy["cost_sensitivity"]["cost_bps"] == [0.0, 5.0, 10.0, 25.0]
        assert 0.0 <= strategy["walk_forward"]["dsr"] <= 1.0


def test_benchmark_view_uses_the_committed_results(built):
    results, _ = built
    assert results["benchmark"]["rows"] == json.loads(BENCHMARK.read_text())["rows"]


def test_page_embeds_results_and_labels_synthetic_data(built):
    results, page = built
    embedded = re.search(r'<script type="application/json" id="results">(.*?)</script>', page, re.S)
    assert json.loads(embedded.group(1).replace("<\\/", "</")) == results
    seed = results["meta"]["data"]["seed"]
    assert f"Synthetic data, seed {seed}, generated by make_fixture.py" in page


def test_every_number_on_the_page_comes_from_results(built):
    results, page = built
    parser = VisibleText()
    parser.feed(page)
    numbers = re.findall(r"-?\d+(?:\.\d+)?", " ".join(parser.chunks))
    serialized = json.dumps(results)
    assert numbers, "page shows no numbers at all"
    for number in numbers:
        assert number in serialized, number
